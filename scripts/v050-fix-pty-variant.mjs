import fs from 'node:fs';
const p='apps/sidewire/src/main.rs';
let s=fs.readFileSync(p,'utf8');
const wrong='    Pty {\n        device: Option<String>,\n        program: String,\n        args: Vec<String>,\n        run_as: RunAs,\n        cols: u16,\n        rows: u16,\n        term: String,\n    },\n';
s=s.replace(wrong,'');
const cr=s.indexOf('enum ControlRequest {');
const f=s.indexOf('    Forward {',cr);
if(cr<0||f<0) throw new Error('ControlRequest Forward marker missing');
s=s.slice(0,f)+wrong+s.slice(f);
fs.writeFileSync(p,s);

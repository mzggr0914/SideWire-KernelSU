import fs from 'node:fs';
let s=fs.readFileSync('Cargo.toml','utf8');
s=s.replace('version = "0.4.0"','version = "0.5.0"');
fs.writeFileSync('Cargo.toml',s);
let prop=fs.readFileSync('module/module.prop','utf8');
prop=prop.replace('version=0.4.0','version=0.5.0').replace('versionCode=6','versionCode=7');
prop=prop.replace(/description=.*/,'description=Native Android bridge with real PTY shell, root/shell execution, streaming logcat, file transfer, app tools, and TCP forwarding.');
fs.writeFileSync('module/module.prop',prop);
let customize=fs.readFileSync('module/customize.sh','utf8').replace(/SideWire 0\.4\.0/g,'SideWire 0.5.0');
fs.writeFileSync('module/customize.sh',customize);
